import yaml

from xvm_control import cli, golden, profile

from .golden_capture import write

CV = r"HKLM\SOFTWARE\Microsoft\Windows NT\CurrentVersion"
TCPIP = r"HKLM\SYSTEM\CurrentControlSet\Services\Tcpip\Parameters"
COMPUTERNAME = r"HKLM\SYSTEM\CurrentControlSet\Control\ComputerName\ComputerName"


def test_build_base(tmp_path):
    base, notes = golden.build_base(write(tmp_path / "cap"), "windows-2022")
    assert base["kind"] == "base-image" and base["os"] == "windows"
    assert base["source"]["golden_capture"] == "cap"
    assert base["os_info"] == {
        "product_name": "Windows Server 2022 Standard Evaluation",
        "version": "10.0",
        "build": "20348",
        "edition": "ServerStandardEval",
        "display_version": "21H2",
        "ubr": 0xA2B,
        "architecture": "x86_64",
        "install_date": "2026-01-01T00:00:00Z",
        "locale": "en-US",
        "timezone": "UTC",
    }
    assert base["hardware"] == {
        "cpu": {
            "name": "Example CPU",
            "vendor": "GenuineIntel",
            "cores": 4,
            "logical_processors": 8,
            "mhz": 2400,
        },
        "memory_mb": 4096,
        "system": {"manufacturer": "Example Systems", "model": "Virtual Machine"},
        "bios": {"vendor": "Example BIOS", "version": "1.0", "release_date": "2024-01-01"},
    }
    assert base["network"] == {
        "interfaces": [{"name": "Ethernet0", "description": "Example NIC", "dhcp": True}]
    }
    assert f"{CV}: value 'Odd' of type hex(0)" in " ".join(notes)


def test_identity_is_left_out(tmp_path):
    base, _ = golden.build_base(write(tmp_path / "cap"), "windows-2022")
    keys = base["registry"]["keys"]
    assert keys[COMPUTERNAME] == {"Other": {"type": "REG_SZ", "data": "kept"}}
    assert set(keys[TCPIP]) == {"SearchList"}
    assert not any("Interfaces" in k for k in keys)
    text = yaml.safe_dump(base)
    for secret in (
        "GOLDEN-VM",
        "198.51.100.7",
        "02:00:00:00:00:01",
        "02-00-00-00-00-01",
        "SERIAL-123",
    ):
        assert secret not in text


def test_agent_and_test_user_are_left_out(tmp_path):
    base, _ = golden.build_base(write(tmp_path / "cap"), "windows-2022")
    assert [s["name"] for s in base["services"]] == ["EventLog", "W32Time"]
    assert not any("WazuhSvc" in k for k in base["registry"]["keys"])
    assert [u["name"] for u in base["users"]] == ["Administrator", "Guest"]
    names = [s["name"] for s in base["software"]]
    assert names == ["Example Tool", "Legacy 32-bit App"]  # no Wazuh, no system component


def test_accounts_and_software_details(tmp_path):
    base, _ = golden.build_base(write(tmp_path / "cap"), "windows-2022")
    admin = base["users"][0]
    assert admin == {
        "name": "Administrator",
        "enabled": True,
        "sid": "S-1-5-21-1-2-3-500",
        "groups": ["Administrators"],
    }  # the domain group member is ignored
    tool, legacy = base["software"]
    assert tool == {
        "name": "Example Tool",
        "architecture": "x86_64",
        "version": "1.2.3",
        "vendor": "Example Corp",
        "install_date": "2026-01-02",
    }
    assert legacy["architecture"] == "x86"
    w32 = base["services"][1]
    assert w32["state"] == "stopped" and w32["start_mode"] == "manual"
    assert w32["account"] == "NT AUTHORITY\\LocalService"


def test_profile_resolves_on_generated_base(tmp_path):
    base, _ = golden.build_base(write(tmp_path / "cap"), "windows-2022")
    host = {
        "schema": 1,
        "kind": "host-profile",
        "name": "h1",
        "base": "windows-2022",
        "os": "windows",
        "identity": {"hostname": "H1"},
        "registry": {"keys": {COMPUTERNAME: {"ComputerName": {"type": "REG_SZ", "data": "H1"}}}},
    }
    r = profile.resolve(host, base)
    assert r["registry"]["keys"][COMPUTERNAME]["ComputerName"]["data"] == "H1"


def test_tampered_capture_is_rejected(tmp_path):
    cap = write(tmp_path / "cap")
    (cap / "host/os.json").write_text("{}")
    rc = cli.main(["base-from-golden", str(cap), "--name", "x", "--out", str(tmp_path / "x.yaml")])
    assert rc == 1
    assert not (tmp_path / "x.yaml").exists()


def test_cli_writes_valid_base(tmp_path, capsys):
    cap = write(tmp_path / "cap")
    out = tmp_path / "bases" / "windows-2022.yaml"
    assert (
        cli.main(["base-from-golden", str(cap), "--name", "windows-2022", "--out", str(out)]) == 0
    )
    assert out.read_text().startswith("# Generated by xvm-profile base-from-golden")
    assert profile.load(out)["name"] == "windows-2022"
    assert "note:" in capsys.readouterr().err
