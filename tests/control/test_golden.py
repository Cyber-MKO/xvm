def test_profile_resolves_on_generated_base(tmp_path):
    base, _ = golden.build_base(write(tmp_path / "cap"), "windows-2022")
    host = {
        "schema": 1,
        "kind": "host-profile",
        "name": "h1",
        "base": "windows-2022",
        "os": "windows",
        "identity": {"hostname": "H1"},
        "registry": {"keys": {COMPUTERNAME: {"ComputerName": {"type": "REG_SZ", "data": "H1"}}}},
    }
    r = profile.resolve(host, base)
    assert r["registry"]["keys"][COMPUTERNAME]["ComputerName"]["data"] == "H1"


def test_tampered_capture_is_rejected(tmp_path):
    cap = write(tmp_path / "cap")
    (cap / "host/os.json").write_text("{}")
    rc = cli.main(["base-from-golden", str(cap), "--name", "x", "--out", str(tmp_path / "x.yaml")])
    assert rc == 1
    assert not (tmp_path / "x.yaml").exists()


def test_cli_writes_valid_base(tmp_path, capsys):
    cap = write(tmp_path / "cap")
    out = tmp_path / "bases" / "windows-2022.yaml"
    assert (
        cli.main(["base-from-golden", str(cap), "--name", "windows-2022", "--out", str(out)]) == 0
    )
    assert out.read_text().startswith("# Generated by xvm-profile base-from-golden")
    assert profile.load(out)["name"] == "windows-2022"
    assert "note:" in capsys.readouterr().err


def test_processes_from_capture(tmp_path):
    base, notes = golden.build_base(write(tmp_path / "cap"), "windows-2022")
    procs = {p["id"]: p for p in base["processes"]}
    # The capture's PowerShell tree and the agent's processes are not part of the OS.
    assert list(procs) == [
        "system-idle-process",
        "system",
        "smss",
        "svchost",
        "svchost-2",
        "explorer",
    ]
    assert procs["system-idle-process"]["pid"] == 0
    assert procs["system"] == {
        "id": "system",
        "image": "System",
        "pid": 4,
        "user": "NT AUTHORITY\\SYSTEM",
        "session": 0,
        "start_offset_s": 0,
    }
    assert procs["smss"]["parent"] == "system"
    assert procs["smss"]["path"] == "C:\\Windows\\System32\\smss.exe"
    assert procs["svchost"]["command_line"] == "svchost.exe -k DcomLaunch"
    assert procs["svchost-2"]["start_offset_s"] == 6.25
    assert "pid" not in procs["svchost"]  # the engine assigns PIDs per host
    assert "parent" not in procs["explorer"]  # its parent was not captured
    assert procs["explorer"]["session"] == 1
    assert procs["explorer"]["user"] == ".\\Administrator"
    assert not any(n.startswith("capture PowerShell") for n in notes)
    # The boot time itself is per host and stays out of the base.
    assert "last_boot" not in base["os_info"]


def test_files_from_capture(tmp_path):
    base, notes = golden.build_base(write(tmp_path / "cap"), "windows-2022")
    files = {f["path"]: f for f in base["files"]}
    assert files["C:\\Windows"] == {
        "path": "C:\\Windows",
        "type": "dir",
        "created": "2026-01-01T00:00:00Z",
        "modified": "2026-10-16T08:00:00Z",
        "accessed": "2026-10-16T09:00:00Z",
    }
    hosts = files["C:\\Windows\\System32\\drivers\\etc\\hosts"]
    assert hosts["size"] == 824 and hosts["sha256"] == "ab" * 32
    assert hosts["attributes"] == ["archive"]
    assert "content" not in hosts  # metadata only, never vendor bytes
    assert files["C:\\Windows\\regedit.exe"]["attributes"] == ["archive", "readonly", "system"]
    assert "\\\\?\\C:\\long\\path.txt" not in files
    assert any("long\\path.txt" in n for n in notes)


def test_converted_base_runs_in_compile(tmp_path):
    base, _ = golden.build_base(write(tmp_path / "cap"), "windows-2022")
    bases, hosts = tmp_path / "bases", tmp_path / "hosts"
    bases.mkdir()
    hosts.mkdir()
    (bases / "windows-2022.yaml").write_text(yaml.safe_dump(base))
    (hosts / "h1.yaml").write_text(
        yaml.safe_dump(
            {
                "schema": 1,
                "kind": "host-profile",
                "name": "h1",
                "base": "windows-2022",
                "os": "windows",
                "identity": {"hostname": "H1"},
                "os_info": {"last_boot": "2026-10-17T06:00:00Z"},
            }
        )
    )
    index = profile.compile_tree([bases], [hosts], tmp_path / "out")
    assert index["hosts"] == ["h1"]


