def test_identity_is_left_out(tmp_path):
    base, _ = golden.build_base(write(tmp_path / "cap"), "windows-2022")
    keys = base["registry"]["keys"]
    assert keys[COMPUTERNAME] == {"Other": {"type": "REG_SZ", "data": "kept"}}
    assert set(keys[TCPIP]) == {"SearchList"}
    assert not any("Interfaces" in k for k in keys)
    text = yaml.safe_dump(base)
    for secret in (
        "GOLDEN-VM",
        "198.51.100.7",
        "02:00:00:00:00:01",
        "02-00-00-00-00-01",
        "SERIAL-123",
    ):
        assert secret not in text


