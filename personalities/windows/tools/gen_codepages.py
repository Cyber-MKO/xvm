#!/usr/bin/env python3
"""Generate src/codepage/tables.rs from Unicode's Microsoft mapping files.

Inputs are in data/codepages/, as published under
https://www.unicode.org/Public/MAPPINGS/VENDORS/MICSFT/ (Unicode License
v3, see data/codepages/LICENSE):

| File | Format | Gives |
| --- | --- | --- |
| WindowsBestFit/bestfitNNNN.txt | CODEPAGE, CPINFO, MBTABLE, WCTABLE | Both ways, with best fit |
| PC/CPNNN.TXT | Format A: byte, Unicode, comment | Bytes to Unicode; reverse is the inverse |

Only single-byte code pages are supported.

Usage: tools/gen_codepages.py (from personalities/windows)
"""

import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent.parent
DATA = HERE / "data" / "codepages"
OUT = HERE / "src" / "codepage" / "tables.rs"


def fields(line, comment):
    return line.split(comment, 1)[0].split()


def best_fit(path):
    """(number, default byte, default Unicode, to_unicode, from_unicode)."""
    lines = path.read_bytes().decode("latin-1").splitlines()
    number = default_byte = default_unicode = None
    to_unicode, from_unicode = {}, {}
    section = None
    for line in lines:
        f = fields(line, ";")
        if not f:
            continue
        tag = f[0]
        if tag == "CODEPAGE":
            number = int(f[1])
        elif tag == "CPINFO":
            if f[1] != "1":
                sys.exit(f"{path.name}: only single-byte code pages are supported")
            default_byte, default_unicode = int(f[2], 16), int(f[3], 16)
        elif tag in ("MBTABLE", "WCTABLE"):
            section = tag
        elif tag == "ENDCODEPAGE":
            break
        elif section == "MBTABLE":
            to_unicode[int(f[0], 16)] = int(f[1], 16)
        elif section == "WCTABLE":
            from_unicode[int(f[0], 16)] = int(f[1], 16)
    return number, default_byte, default_unicode, to_unicode, from_unicode


def format_a(path, number):
    to_unicode = {}
    for line in path.read_bytes().decode("latin-1").splitlines():
        f = fields(line, "#")
        if len(f) == 2:
            to_unicode[int(f[0], 16)] = int(f[1], 16)
    from_unicode = {}
    for byte, unit in sorted(to_unicode.items()):
        from_unicode.setdefault(unit, byte)
    return number, 0x3F, 0x3F, to_unicode, from_unicode


def emit(tables):
    out = [
        "//! Generated by tools/gen_codepages.py from data/codepages/. Do not edit.",
        "",
        "use super::SingleByte;",
        "",
    ]
    names = []
    for number, default_byte, default_unicode, to_unicode, from_unicode in tables:
        name = f"CP{number}"
        names.append(name)
        # Bytes without a mapping decode to the default Unicode character.
        mb = [to_unicode.get(b, default_unicode) for b in range(256)]
        defined = [b in to_unicode for b in range(256)]
        wc = sorted(from_unicode.items())
        out.append(f"pub(super) static {name}: SingleByte = SingleByte {{")
        out.append(f"    number: {number},")
        out.append(f"    default_byte: 0x{default_byte:02x},")
        out.append(f"    default_unicode: 0x{default_unicode:04x},")
        out.append("    to_unicode: [")
        for i in range(0, 256, 8):
            row = ", ".join(f"0x{u:04x}" for u in mb[i : i + 8])
            out.append(f"        {row},")
        out.append("    ],")
        out.append("    defined: [")
        for i in range(0, 256, 16):
            row = ", ".join("true" if d else "false" for d in defined[i : i + 16])
            out.append(f"        {row},")
        out.append("    ],")
        out.append("    from_unicode: &[")
        for unit, byte in wc:
            out.append(f"        (0x{unit:04x}, 0x{byte:02x}),")
        out.append("    ],")
        out.append("};")
        out.append("")
    refs = ", ".join("&" + n for n in names)
    out.append(f"pub(super) static ALL: [&SingleByte; {len(names)}] = [{refs}];")
    return "\n".join(out) + "\n"


def main():
    tables = [best_fit(DATA / "bestfit1252.txt"), format_a(DATA / "CP437.TXT", 437)]
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(emit(tables))
    print(f"wrote {OUT.relative_to(HERE)}")


if __name__ == "__main__":
    main()
