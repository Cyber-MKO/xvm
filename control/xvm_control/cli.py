"""Command line: xvm-profile validate | resolve | base-from-golden."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import yaml

from . import golden, profile

DEFAULT_BASES = Path("control/profiles/bases")


def _validate(args: argparse.Namespace) -> int:
    failed = False
    for path in args.files:
        try:
            doc = profile.load(path)
            if doc["kind"] == "host-profile":
                profile.resolve_file(path, args.bases or [DEFAULT_BASES])
        except profile.ProfileError as exc:
            print(exc, file=sys.stderr)
            failed = True
        else:
            print(f"ok: {path}")
    return 1 if failed else 0


def _resolve(args: argparse.Namespace) -> int:
    try:
        host = profile.resolve_file(args.file, args.bases or [DEFAULT_BASES])
    except profile.ProfileError as exc:
        print(exc, file=sys.stderr)
        return 1
    if args.format == "json":
        print(json.dumps(host, indent=2))
    else:
        print(yaml.safe_dump(host, sort_keys=False, allow_unicode=True), end="")
    return 0


def _base_from_golden(args: argparse.Namespace) -> int:
    try:
        base, notes = golden.build_base(args.capture, args.name, args.description)
    except (golden.ConvertError, golden.regfile.RegFileError) as exc:
        print(exc, file=sys.stderr)
        return 1
    out = args.out or DEFAULT_BASES / f"{args.name}.yaml"
    out.parent.mkdir(parents=True, exist_ok=True)
    header = (
        f"# Generated by xvm-profile base-from-golden from {args.capture.name}.\n"
        "# Do not edit by hand: change the capture or the converter and regenerate.\n"
    )
    out.write_text(
        header + yaml.safe_dump(base, sort_keys=False, allow_unicode=True), encoding="utf-8"
    )
    for n in notes:
        print(f"note: {n}", file=sys.stderr)
    print(out)
    return 0


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(prog="xvm-profile", description=__doc__)
    sub = p.add_subparsers(dest="cmd", required=True)
    v = sub.add_parser("validate", help="check base images and host profiles")
    v.add_argument("files", type=Path, nargs="+")
    v.add_argument("--bases", type=Path, action="append", help="base image folder (repeatable)")
    v.set_defaults(func=_validate)
    r = sub.add_parser("resolve", help="print a host profile merged onto its base")
    r.add_argument("file", type=Path)
    r.add_argument("--bases", type=Path, action="append", help="base image folder (repeatable)")
    r.add_argument("--format", choices=["yaml", "json"], default="yaml")
    r.set_defaults(func=_resolve)
    g = sub.add_parser("base-from-golden", help="build a Windows base image from a golden capture")
    g.add_argument("capture", type=Path, help="capture folder (with manifest.json)")
    g.add_argument("--name", required=True, help="base image name, for example windows-2022")
    g.add_argument("--description")
    g.add_argument("--out", type=Path, help=f"output file (default {DEFAULT_BASES}/NAME.yaml)")
    g.set_defaults(func=_base_from_golden)
    args = p.parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    raise SystemExit(main())
